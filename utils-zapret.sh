#!/usr/bin/env bash
#
# УСТАРЕЛО. Оставлено ради совместимости и будет удалено.
#
# Нужно по двум причинам:
#   1. Алиас zapret-utils в rc-файлах уже установленных пользователей
#      указывает на этот путь.
#   2. Апдейтер старых версий отказывается ставить обновление, если не
#      находит в архиве utils-zapret.sh, install.sh и setup.sh. Убрать эти
#      файлы сразу - значит навсегда лишить обновлений всех, кто ещё не
#      перешёл на новую версию.
#
# Актуальная команда: zapret-manager
set -euo pipefail

SELF_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"

printf '[ ! ] utils-zapret.sh устарел, используйте команду zapret-manager\n' >&2

exec "$SELF_DIR/bin/zapret-manager" "$@"
